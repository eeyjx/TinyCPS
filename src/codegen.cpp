// TinyCPS C11 backend and human-readable AST printer.
// This is source-to-source code generation: AST semantics are expressed
// as C statements, and a separate C compiler produces native machine code.

#include "compiler.hpp"

#include <sstream>
#include <stdexcept>
#include <string>
#include <unordered_map>
#include <vector>

namespace tinycps {
namespace {

// Only arithmetic operators that can appear inside expression ASTs are
// mapped to C syntax here; unsupported operator kinds are programming errors.
std::string op_to_string(TokenKind kind) {
    switch (kind) {
        case TokenKind::Plus: return "+";
        case TokenKind::Minus: return "-";
        case TokenKind::Star: return "*";
        case TokenKind::Slash: return "/";
        default: throw std::logic_error("invalid arithmetic operator");
    }
}

// The generator walks statements in source order and emits a complete
// C11 translation unit with main() as the entry point.
class CGenerator {
public:
    std::string generate(const Program& program) {
        out_ << "/* Generated by TinyCPS: general source-to-C code generation study. */\n"
             << "/* Compile this C11 file with a C compiler; it is not LLVM IR. */\n"
             << "#include <stdio.h>\n\n"
             << "int main(void) {\n";
        for (const auto& stmt : program) emit_stmt(*stmt, 1);
        out_ << "    return 0;\n}\n";
        return out_.str();
    }
private:
    std::ostringstream out_;
    // Unique per-loop IDs keep generated counters distinct in nested loops.
    std::size_t next_loop_{0};
    std::size_t next_variable_{0};
    std::vector<std::unordered_map<std::string, std::string>> scopes_{1};

    // Each lexical declaration gets a unique C identifier. This is required
    // for correct shadowing: in `let x=3; repeat(1){let x=x+8;}` the inner
    // initializer must read the OUTER x, not its own uninitialized slot.
    std::string lookup(const std::string& name) const {
        for (auto it = scopes_.rbegin(); it != scopes_.rend(); ++it) {
            auto found = it->find(name);
            if (found != it->end()) return found->second;
        }
        throw std::logic_error("missing binding: " + name);
    }
    std::string emit_expr(const Expr& expr) {
        if (auto* n = dynamic_cast<const NumberExpr*>(&expr)) return n->value;
        if (auto* n = dynamic_cast<const NameExpr*>(&expr)) return lookup(n->name);
        if (auto* n = dynamic_cast<const UnaryExpr*>(&expr))
            return "(-" + emit_expr(*n->operand) + ")";
        if (auto* n = dynamic_cast<const BinaryExpr*>(&expr))
            return "(" + emit_expr(*n->left) + " " + op_to_string(n->op) + " " + emit_expr(*n->right) + ")";
        throw std::logic_error("unknown expression kind");
    }

    // Indentation is for readability only and does not change C semantics.
    void line(int depth, const std::string& text) {
        out_ << std::string(static_cast<std::size_t>(depth) * 4, ' ') << text << '\n';
    }
    // Every TinyCPS statement lowers to one or more C statements.
    void emit_stmt(const Stmt& stmt, int depth) {
        if (auto* n = dynamic_cast<const LetStmt*>(&stmt)) {
            const auto initializer = emit_expr(*n->value);
            const auto target = "tc_user_" + n->name + "_" + std::to_string(next_variable_++);
            line(depth, "long long " + target + " = " + initializer + ";");
            scopes_.back()[n->name] = target;
            return;
        }
        if (auto* n = dynamic_cast<const SetStmt*>(&stmt)) {
            line(depth, lookup(n->name) + " = " + emit_expr(*n->value) + ";");
            return;
        }
        // Printing an expression has a side effect but does not assign its
        // value back to any variable. The cast matches printf's %lld format.
        if (auto* n = dynamic_cast<const PrintStmt*>(&stmt)) {
            line(depth, "printf(\"%lld\\n\", (long long)(" + emit_expr(*n->value) + "));" );
            return;
        }
        if (auto* n = dynamic_cast<const RepeatStmt*>(&stmt)) {
            const auto index = next_loop_++;
            const std::string counter = "tc_iter_" + std::to_string(index);
            const std::string count = "tc_count_" + std::to_string(index);
            // The extra block mirrors TinyCPS lexical scope and keeps loop
            // temporaries local to this specific repeat statement.
            line(depth, "{");
            // Capture repeat count exactly once at loop entry (avoid surprises
            // if a variable used in the count changes inside the loop).
            line(depth + 1, "/* Evaluate the repeat count once at loop entry. */");
            line(depth + 1, "const long long " + count + " = " + emit_expr(*n->count) + ";");
            line(depth + 1, "for (long long " + counter + " = 0; " + counter + " < " + count + "; ++" + counter + ") {");
            scopes_.emplace_back();
            for (const auto& nested : n->body) emit_stmt(*nested, depth + 2);
            scopes_.pop_back();
            line(depth + 1, "}");
            line(depth, "}");
            return;
        }
        throw std::logic_error("unknown statement kind");
    }
};

void indent(std::ostringstream& out, int depth) {
    out << std::string(static_cast<std::size_t>(depth) * 2, ' ');
}
// Debugging view for students: reveals the tree built by the parser.
void dump_expression(std::ostringstream& out, const Expr& expr, int depth) {
    indent(out, depth);
    if (auto* n = dynamic_cast<const NumberExpr*>(&expr)) {
        out << "Number(" << n->value << ")\n";
    } else if (auto* n = dynamic_cast<const NameExpr*>(&expr)) {
        out << "Name(" << n->name << ")\n";
    } else if (auto* n = dynamic_cast<const UnaryExpr*>(&expr)) {
        out << "Unary(" << op_to_string(n->op) << ")\n";
        dump_expression(out, *n->operand, depth + 1);
    } else if (auto* n = dynamic_cast<const BinaryExpr*>(&expr)) {
        out << "Binary(" << op_to_string(n->op) << ")\n";
        dump_expression(out, *n->left, depth + 1);
        dump_expression(out, *n->right, depth + 1);
    }
}
// Statement AST nodes contain expression subtrees and possibly nested blocks.
void dump_statement(std::ostringstream& out, const Stmt& stmt, int depth) {
    indent(out, depth);
    if (auto* n = dynamic_cast<const LetStmt*>(&stmt)) {
        out << "Let(" << n->name << ")\n";
        dump_expression(out, *n->value, depth + 1);
    } else if (auto* n = dynamic_cast<const SetStmt*>(&stmt)) {
        out << "Set(" << n->name << ")\n";
        dump_expression(out, *n->value, depth + 1);
    } else if (auto* n = dynamic_cast<const PrintStmt*>(&stmt)) {
        out << "Print\n";
        dump_expression(out, *n->value, depth + 1);
    } else if (auto* n = dynamic_cast<const RepeatStmt*>(&stmt)) {
        out << "Repeat\n";
        dump_expression(out, *n->count, depth + 1);
        for (const auto& inner : n->body) dump_statement(out, *inner, depth + 1);
    }
}

}  // namespace

// Public backend entry point. A new generator is used for each compilation.
std::string generate_c(const Program& program) {
    return CGenerator{}.generate(program);
}
std::string dump_ast(const Program& program) {
    std::ostringstream out;
    out << "Program\n";
    for (const auto& stmt : program) dump_statement(out, *stmt, 1);
    return out.str();
}

}  // namespace tinycps
